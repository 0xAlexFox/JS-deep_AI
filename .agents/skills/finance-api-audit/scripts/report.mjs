const levels = { error: 'Ошибка совместимости', warning: 'Предупреждение' };
const escape = (value) => String(value).replace(/[\r\n\t]/g, ' ').replace(/[\\`*_{}\[\]()<>|]/g, (char) => `\\${char}`);

export function renderMarkdown(report) {
  const time = new Intl.DateTimeFormat('ru-RU', {
    dateStyle: 'long', timeStyle: 'medium', timeZone: 'Europe/Moscow',
  }).format(new Date(report.checkedAt));
  const lines = [
    '# Аудит ответов финансовых API', '',
    `Проверено: ${time} МСК. UTC: ${report.checkedAt}.`,
    `Режим: ${report.mode === 'live' ? 'текущие ответы серверов' : 'локальный снимок / тестовые данные'}.`,
    `Полнота: ${report.complete ? 'все три источника получены; ограничения справочника/объёма не обнаружены' : 'проверка ограничена; см. источники и замечания'}.`, '',
    '## Краткий результат', '',
    `Групп ошибок совместимости: ${report.summary.error}; групп предупреждений: ${report.summary.warning}. Это число типов замечаний по источникам, а не число платежей.`,
    `Обнаруженные коды валют: ${report.currencies.map(escape).join(', ') || 'не удалось определить / оплаченных продаж нет'}.`, '',
    'Ошибки совместимости означают несоответствие требованиям текущего клиента. Без согласованной спецификации API это не всегда доказывает ошибку backend. Предупреждения требуют проверки или согласования.', '',
    'Финансовые endpoints: /api/finance1 и /api/finance2 на cpa-server-vtel.onrender.com. Курсы: open.er-api.com/v6/latest/USD. Секретные заголовки не включены.', '',
    '## Источники и объём проверки', '',
    '| Источник | HTTP | Получено записей | Проверено | Учтённых продаж |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const source of report.sources) lines.push(`| ${source.name} | ${source.status ?? 'нет данных'} | ${source.records ?? 'не применимо / недоступно'} | ${source.name === 'rates' ? '-' : source.checked} | ${source.name === 'rates' ? '-' : source.paid} |`);
  lines.push('', 'У finance1 учтены только точные статусы paid; finance2 рассматривается как список оплаченных продаж. Полные ответы, идентификаторы и персональные поля в отчёт не включены.', '', '## Замечания backend-разработчикам', '');
  if (!report.findings.length) lines.push('В проверенных данных перечисленные проверки не выявили замечаний. Это не доказательство отсутствия проблем в других ответах или сценариях.', '');
  for (const [index, item] of report.findings.entries()) {
    lines.push(`### ${index + 1}. ${item.title}`, '',
      `Уровень: ${levels[item.severity]}. Источник: ${item.source}. Правило: ${item.rule}. Срабатываний: ${item.count}.`, '',
      `Влияние: ${item.impact}`, '', `Рекомендация: ${item.recommendation}`, '', 'Примеры (максимум 5):', '');
    for (const example of item.examples) lines.push(`- ${escape(example.path)}: ${escape(example.evidence || 'см. описание правила')}`);
    lines.push('');
  }
  lines.push('## Вопросы к контракту API', '',
    '- Согласовать список статусов и точный смысл «оплачено» у обоих источников.',
    '- Согласовать перечень валют, регистр кодов, минимальные денежные единицы и допустимость специальных/исторических кодов.',
    '- Уточнить правила возвратов и представления сумм. Ограничение клиента в два знака не является общим правилом всех валют.',
    '- Для finance2 уточнить, нужны ли объектные записи с ID, статусом и датой: в строковом формате нельзя надёжно проверить дубли и период.', '',
    '## Справочник и границы выводов', '',
    `Справочник: ${report.reference.source ?? 'недоступен'}.`,
    `Дата публикации: ${report.reference.publishedAt ?? 'неизвестна'}; получен: ${report.reference.retrievedAt ?? 'неизвестно'}.`, '',
    'Отсутствие кода в текущем списке ISO 4217 не означает автоматически, что он никогда не существовал. Отсутствие курса не означает отсутствия валюты. Полный enum статусов, исторические платежи, пагинация и все сценарии сервера этой выборкой не подтверждаются.', '',
    'Проверка читает ответы и ничего не исправляет на сервере или в приложении. Перед передачей отчёта убедитесь, что получатель имеет право видеть приведённые минимальные примеры.', '',
  );
  return lines.join('\n');
}
